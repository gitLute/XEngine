namespace XEngine.Windowing;

/// <summary>
/// Источник времени кадра.
/// </summary>
/// <remarks>
/// Часы только измеряют: они не решают, сколько шагов симуляции нужно, и не
/// ограничивают время кадра. Ограничение — дело <see cref="FixedStepper"/>,
/// потому что ограничивать нечего, пока время не попало в аккумулятор.
/// <para>
/// Владение часами разнесено так же, как владение кадром и шагом (11.3):
/// настенное время читает только кадр, а симуляция получает уже готовое
/// значение шага.
/// </para>
/// </remarks>
public interface IFrameClock
{
    /// <summary>
    /// Текущее время в секундах. Монотонно возрастает.
    /// </summary>
    double NowSeconds { get; }

    /// <summary>
    /// Запоминает текущее время как начало кадра и возвращает время, прошедшее
    /// с прошлого такого вызова.
    /// </summary>
    /// <returns>Время кадра в секундах; ноль у первого вызова.</returns>
    double BeginFrame();
}