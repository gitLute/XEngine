namespace XEngine.Windowing;

/// <summary>
/// То, что цикл кадра вызывает: шаг симуляции и отрисовку.
/// </summary>
/// <remarks>
/// Цикл не знает, что находится внутри: ни ECS, ни кадров рендера на этапе 3
/// ещё не существует. Интерфейс отделён от цикла по той же причине, по какой
/// отделён <see cref="IWindowBackend"/> от окна: цикл должен проверяться
/// заглушкой, а не настоящей сценой (17.6).
/// <para>
/// На этапе 5 реализация цели — конвейер систем; на этапе 4
/// <see cref="Render"/> замыкается на пассы рендера. На этапе 3 обе операции
/// остаются пустыми, и это осознанно: подменять их заглушками в тестах нужно
/// раньше, чем появятся настоящие подсистемы.
/// </para>
/// </remarks>
public interface IFrameLoopTarget
{
    /// <summary>
    /// Выполняет один шаг симуляции.
    /// </summary>
    /// <remarks>
    /// Вызывается от нуля до <see cref="Core.Configuration.SimulationConfig.MaxSubSteps"/> раз за
    /// кадр, строго до <see cref="Render"/>. Именно фиксированный шаг даёт
    /// независимость результата от частоты кадров (инвариант 6a).
    /// </remarks>
    /// <param name="stepSeconds">
    /// Длительность шага в секундах. Всегда одна и та же величина: шаг симуляции
    /// не зависит от времени кадра, иначе результат зависел бы от частоты
    /// кадров.
    /// </param>
    /// <param name="stepNumber">
    /// Номер шага в текущем кадре, начиная с нуля.
    /// </param>
    void Simulate(double stepSeconds, int stepNumber);

    /// <summary>
    /// Отрисовывает кадр.
    /// </summary>
    /// <remarks>
    /// Вызывается ровно один раз за кадр, когда шаги уже выполнены: кадр рисует
    /// результат симуляции, а не промежуточное состояние.
    /// </remarks>
    /// <param name="context">Данные кадра: номер, время, множитель интерполяции, размер фреймбуфера.</param>
    void Render(in FrameContext context);
}