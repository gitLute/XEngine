namespace XEngine.Windowing;

/// <summary>
/// Окно: размер, заголовок, фокус, признак закрытия и обмен событиями с
/// платформой.
/// </summary>
/// <remarks>
/// Контракт намеренно узкий. Всё, что не касается окна как такового, в нём
/// отсутствует: создание GPU-ресурсов, своп буферов и рисование принадлежат
/// графике (10.2, 16.1), ввод — подсистеме ввода (13). Иначе окно стало бы
/// местом, где сходятся все подсистемы, и подменить его в тесте было бы
/// невозможно.
/// <para>
/// Метод обмена событиями назван <see cref="PollEvents"/>, а не
/// <c>DoEvents</c>: он опрашивает платформу один раз и возвращает управление,
/// тогда как Silk.NET внутри своего цикла блокируется в ожидании событий.
/// Различие важно: цикл кадра сам решает, когда опрашивать события, и не
/// должен засыпать внутри шага.
/// </para>
/// </remarks>
public interface IWindow : IDisposable
{
    /// <summary>
    /// Заголовок окна.
    /// </summary>
    string Title { get; set; }

    /// <summary>
    /// Размер окна в экранных координатах.
    /// </summary>
    /// <remarks>
    /// Не путать с <see cref="FramebufferSize"/>: на экране с масштабированием
    /// они различаются, и рамка для viewport берётся у второго.
    /// </remarks>
    WindowSize Size { get; set; }

    /// <summary>
    /// Размер области рисования в пикселях.
    /// </summary>
    WindowSize FramebufferSize { get; }

    /// <summary>
    /// Имеет ли окно фокус ввода.
    /// </summary>
    /// <remarks>
    /// Потеря фокуса означает, что состояние клавиатуры больше не доверять:
    /// системные сочетания клавиш уходят мимо приложения. Ввод обязан это
    /// учитывать (13).
    /// </remarks>
    bool IsFocused { get; }

    /// <summary>
    /// Просит окно закрыться.
    /// </summary>
    /// <remarks>
    /// Цикл кадра проверяет этот признак и завершается (16.1). Метод
    /// односторонний: окно не сообзывает через него, что закрылось, —
    /// состояние читается в <see cref="IsClosing"/>.
    /// </remarks>
    void RequestClose();

    /// <summary>
    /// Требует ли окно закрытия. Становится <c>true</c> после запроса
    /// закрытия пользователем или вызовом <see cref="RequestClose"/>.
    /// </summary>
    bool IsClosing { get; }

    /// <summary>
    /// Опрашивает платформу: обрабатывает ввод, изменение размера и закрытие.
    /// </summary>
    /// <remarks>
    /// Вызывается один раз в начале кадра. Возвращает управление сразу, в
    /// отличие от <c>Run</c> у Silk.NET, который блокируется.
    /// </remarks>
    void PollEvents();
}