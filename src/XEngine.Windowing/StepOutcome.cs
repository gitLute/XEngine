namespace XEngine.Windowing;

/// <summary>
/// Что произошло со временем шага симуляции (8.3a).
/// </summary>
/// <remarks>
/// Превышение бюджета — это диагностика, а не поведение: прервать шаг нельзя,
/// потому что мир остался бы в промежуточном состоянии, часть тел шагнула бы,
/// а часть нет. Поведение при перегрузке определено отдельно — пределом числа
/// шагов за кадр и сбросом излишка аккумулятора.
/// </remarks>
public enum StepOutcome
{
    /// <summary>
    /// Шаг уложился в бюджет. Ничего не делается.
    /// </summary>
    WithinBudget = 0,

    /// <summary>
    /// Шаг превысил бюджет и продолжает выполняться до конца; включается
    /// диагностика.
    /// </summary>
    OverBudget = 1,

    /// <summary>
    /// Шаг превысил бюджет в несколько раз. Это уже ошибка конфигурации:
    /// бюджет занижен или система слишком тяжёлая.
    /// </summary>
    OverBudgetSeverely = 2,
}