namespace XEngine.Core.Logging;

/// <summary>
/// Уровень важности сообщения. Порядок объявления значим: уровень считается
/// тем важнее, чем позже объявлен, поэтому фильтр — это сравнение.
/// </summary>
public enum LogLevel
{
    /// <summary>
    /// Детализация для диагностики, по умолчанию выключена.
    /// </summary>
    Debug = 0,

    /// <summary>
    /// Обычный ход работы: что было сделано.
    /// </summary>
    Information = 1,

    /// <summary>
    /// Работа продолжается, но условия не штатные: переполнение бюджета,
    /// сброс излишка аккумулятора.
    /// </summary>
    Warning = 2,

    /// <summary>
    /// Работа нарушена: превышение бюджета вчетверо, неверная конфигурация.
    /// </summary>
    Error = 3,
}