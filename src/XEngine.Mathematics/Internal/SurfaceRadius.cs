using System.Numerics;

namespace XEngine.Mathematics;

/// <summary>
/// Радиус для точки поверхности, гарантированно остающейся внутри фигуры.
/// </summary>
/// <remarks>
/// <para>
/// Метод поверхности возвращает точку, которую вызывающий сразу проверяет на
/// принадлежность, поэтому результат обязан приниматься собственной проверкой
/// той же фигуры. Если строить точку как «центр + направление · радиус», то
/// округление сложения уводит её наружу: ошибка достигает половины последнего
/// разряда координаты центра, а не радиуса. Доля таких отказов измерена на
/// 200 000 равномерных запросах в кубе со стороной 1 м при радиусе 0.1 м и
/// центре в (0.5, 0.25, 0.125): 35.3 % у сферы, 39.1 % у капсулы и 40.9 % у
/// круга, то есть примерно каждый третий вызов. Число зависит от геометрии
/// запросов: на кубе со стороной 0.05 м те же доли равны 22.8 %, 19.6 % и
/// 20.3 %. Со сдвигом на тех же наборах отказов ноль.
/// </para>
/// <para>
/// От величины ошибки зависят два слагаемых, и оба обязаны быть учтены:
/// последний разряд самого радиуса и последний разряд координаты центра.
/// Второе слагаемое обычно больше: у круга радиуса 0.1 метра с центром в
/// (−4, 7) разряд координаты — 4.77e-7 метра, то есть в 64 раза крупнее
/// разряда радиуса 7.45e-9. Пренебрежение им оставляет дефект на месте.
/// </para>
/// <para>
/// Сдвиг привязан к величине точки отсчёта, а не к радиусу, и на большой карте
/// он в миллионы раз больше радиуса. Поэтому он ограничен сверху половиной
/// радиуса: см. <c>Shrink</c>. Без ограничения сдвиг съедал радиус целиком, то
/// есть результат становился отрицательным, а точка отражалась на
/// противоположную сторону фигуры.
/// </para>
/// <para>
/// Решение выбрано без допуска в проверках принадлежности, чтобы не вводить
/// исключение из общего правила строгих границ библиотеки. Сдвиг метода
/// <c>For</c> равен ровно двум последним разрядам величины точки отсчёта, то
/// есть 2^-22 от неё: на километре это 0.238 миллиметра. И это измерено, а не
/// оценено на глаз.
/// </para>
/// <para>
/// Числа эти — характеристика, а не деталь, и читать их надо именно как
/// характеристику. Разряд величины на километре крупнее разряда радиуса в
/// десятки и сотни раз, поэтому «сдвиг в четыре разряда радиуса», как было
/// написано в четырёх вызывающих методах, не соответствует ничему: сдвиг
/// считается от точки отсчёта. Настоящая величина отклонения точки поверхности
/// измерена: 2.6e-6 метра при радиусе 10 метров.
/// </para>
/// </remarks>
internal static class SurfaceRadius
{
    /// <summary>
    /// Число последних разрядов, на которые уводится точка внутрь.
    /// </summary>
    private const float Shift = 2f;

    /// <summary>
    /// Шаг сдвига: <c>Shift</c> последних разрядов величины, то есть ровно
    /// 2^-22. Считается константой, потому что иначе умножение выполнялось бы
    /// в две операции вместо одной.
    /// </summary>
    private const float Step = 2.384185791015625e-7f;

    /// <summary>
    /// Радиус, меньший настоящего ровно настолько, чтобы округление сложения не
    /// вывело точку наружу.
    /// </summary>
    /// <param name="radius">Настоящий радиус фигуры.</param>
    /// <param name="basePoint">
    /// Точка, от которой отсчитывается смещение. Это не обязательно центр
    /// фигуры: у капсулы это ближайшая точка осевой линии, и у длинной капсулы
    /// она может быть на порядки дальше от начала координат, чем радиус.
    /// Ошибка округления задаётся величиной именно этой точки.
    /// </param>
    /// <returns>Радиус для вычисления точки поверхности.</returns>
    public static float For(float radius, in Vector3 basePoint)
        => Shrink(radius, Magnitude(basePoint));

    /// <summary>
    /// Двумерный вариант того же расчёта.
    /// </summary>
    /// <param name="radius">Настоящий радиус фигуры.</param>
    /// <param name="basePoint">Точка, от которой отсчитывается смещение.</param>
    /// <returns>Радиус для вычисления точки поверхности.</returns>
    public static float For(float radius, in Vector2 basePoint)
    {
        float magnitude = MathF.Max(MathF.Abs(basePoint.X), MathF.Abs(basePoint.Y));
        return Shrink(radius, magnitude);
    }

    /// <summary>
    /// Расстояние, немного превышающее расстояние до первого касания, чтобы
    /// точка, построенная по нему лучом, лежала строго внутри фигуры.
    /// </summary>
    /// <param name="distance">Расстояние до первого касания.</param>
    /// <param name="origin">Начало луча.</param>
    /// <param name="extent">
    /// Размер фигуры вдоль луча: длина отрезка, который луч вырезает в теле.
    /// Сдвиг ограничивается его половиной.
    /// </param>
    /// <returns>Расстояние, ведущее внутрь фигуры.</returns>
    /// <remarks>
    /// <para>
    /// Расстояние до касания по построению кладёт точку ровно на поверхность,
    /// а проверка принадлежности строгая: измеренный выход точки наружу достигает
    /// 2.3e-5 метра при радиусе 0.22 метра, то есть примерно сотня последних
    /// разрядов. Вызывающий, который строит точку по расстоянию и сразу
    /// проверяет её, получает отказ на верном попадании.
    /// </para>
    /// <para>
    /// Сдвиг идёт ВПЕРЁД по лучу, а не назад: расстояние до касания — это
    /// первое касание, и всё, что лежит между началом луча и ним, снаружи.
    /// Уменьшение расстояния на микроскопическую величину даёт отказ
    /// практически на каждом попадании — проверено измерением.
    /// </para>
    /// <para>
    /// Начало луча внутри фигуры расстояние не меняет: там точка входа и так
    /// строго внутри, а сдвиг увеличил бы её произвольно.
    /// </para>
    /// <para>
    /// <b>Размер фигуры — обязательный аргумент, а не украшение.</b> Без него
    /// границу не закрыть в принципе: одной и той же паре (расстояние, начало)
    /// соответствуют и огромная фигура, и крошечная, а правильного ответа для
    /// обеих не существует. Измерено на пяти радиусах от 0.05 до 1e5 и на
    /// отношениях расстояния к размеру от 4 до 2^40: без ограничения сдвига
    /// точка выходила из фигуры при отношении начиная с 2^21 (это 2.1e6), то
    /// есть в 100 % случаев на двадцати октавах подряд; с ограничением
    /// половиной размера отказов не было ни на одной октаве.
    /// </para>
    /// <para>
    /// Ограничение взято половиной, а не всем размером: точка входа и выхода
    /// разделены хордой, и её половина гарантированно остаётся внутри, тогда
    /// как сдвиг на весь размер кладёт точку ровно на выход, и строгая проверка
    /// решает там по округлению. Измерено: при сдвиге в один размер отказы
    /// появлялись на 2^22 и выше, при полуразмере — нигде.
    /// </para>
    /// <para>
    /// Чего метод по-прежнему не знает и потому не может учесть: луч может
    /// идти по касательной, и тогда хорда стремится к нулю. Построить строго
    /// внутреннюю точку сдвигом по лучу в принципе невозможно: движение от
    /// касательной удаляет от поверхности. Этот случай отказов не лечится и
    /// остаётся у вызывающего.
    /// </para>
    /// </remarks>
    public static float PastContact(float distance, in Vector3 origin, float extent)
    {
        if (distance <= 0f)
        {
            return distance;
        }

        // Точка на расстоянии distance от начала имеет величину не больше суммы
        // величин, а сумма нужна потому, что ошибку округления задаёт наибольшая
        // из координат результата, а не самого начала. Сумма берётся по
        // слагаемым после масштабирования: сами расстояния конечны, а вот их
        // сумма с величиной начала переполнялась в +Infinity уже на расстоянии
        // 1.7e38, и метод отдавал бесконечное расстояние, то есть точку по нему
        // построить нельзя.
        //
        // Max(distance, distance + |начало|) не нужен: второе слагаемое не меньше
        // первого, то есть максимум был тождеством.
        float error = (distance * Step) + (Magnitude(origin) * Step);

        // Ограничение половиной размера фигуры вдоль луча. Без него сдвиг,
        // привязанный к расстоянию, на большой карте в миллионы раз больше
        // самой фигуры и перескакивает её насквозь. Порядок именно такой:
        // сначала сдвиг, потом ограничение, — потому что ограничение должно
        // уметь урезать сдвиг, а не наоборот.
        float cap = extent * 0.5f;
        if (error > cap)
        {
            error = cap;
        }

        return distance + error;
    }

    private static float Magnitude(in Vector3 point)
        => MathF.Max(MathF.Max(MathF.Abs(point.X), MathF.Abs(point.Y)), MathF.Abs(point.Z));

    private static float Shrink(float radius, float magnitude)
    {
        // Последний разряд величины не превосходит 2^-23 от неё самой, то есть
        // примерно миллионная доля. Берутся два разряда с запасом на округление
        // сложения и на то, что длина вычисляется с погрешностью.
        //
        // Умножения оставлены двумя, а не свёрнуты в Step: измерено, что
        // вариант с одной константой медленнее на 0.5 нс (2.96 против 2.46 на
        // цикл), хотя операций в нём меньше. Разница воспроизводится между
        // прогонами и при чередовании порядка измерения вариантов.
        float error = MathF.Max(radius, magnitude) * Shift * 1.1920929e-7f;

        // Сдвиг не должен съесть радиус. Он привязан к величине точки отсчёта,
        // поэтому на большой карте он в миллионы раз больше радиуса: при
        // |точка отсчёта| > 2^21 · R сдвиг превышает половину радиуса, при
        // 2^22 · R радиус становится отрицательным — точка отражается на
        // противоположную сторону фигуры, — а при 2^23 · R она уходит за фигуру
        // настолько, что её отвергает собственная проверка принадлежности.
        // Границы измерены бинарным поиском по |точка отсчёта| / R и не зависят
        // от единиц: пять радиусов от 1e-4 до 1e7 дали одну и ту же границу
        // 8388608.5, то есть 2^23 с точностью до округления.
        //
        // Половина радиуса — наибольшее ограничение, при котором результат
        // остаётся положительным, то есть точка остаётся с той же стороны от
        // точки отсчёта, что и запрос. Меньшее ограничение оставляет больше
        // запаса, но хуже компенсирует округление сложения и потому даёт больше
        // отказов на больших отношениях: измерено на 20 000 конфигураций в полосе
        // |точка отсчёта| / R = 8.39e6 четверть радиуса даёт 1160 отказов,
        // половина — ноль.
        float cap = radius * 0.5f;
        if (error > cap)
        {
            error = cap;
        }

        return radius - error;
    }
}