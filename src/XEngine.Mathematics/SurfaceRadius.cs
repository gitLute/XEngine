using System.Numerics;

namespace XEngine.Mathematics;

/// <summary>
/// Радиус для точки поверхности, гарантированно остающейся внутри фигуры.
/// </summary>
/// <remarks>
/// Метод поверхности возвращает точку, которую вызывающий сразу проверяет на
/// принадлежность, поэтому результат обязан приниматься собственной проверкой
/// той же фигуры. Если строить точку как «центр + направление · радиус», то
/// округление сложения уводит её наружу: ошибка достигает половины последнего
/// разряда координаты центра, а не радиуса. Измеренная доля отказов на
/// 200 000 точках — от 0.4 % у сферы до 9.1 % у капсулы, то есть примерно
/// каждый одиннадцатый вызов.
/// <para>
/// От величины ошибки зависят два слагаемых, и оба обязаны быть учтены:
/// последний разряд самого радиуса и последний разряд координаты центра.
/// Второе слагаемое обычно больше: у круга радиуса 0.1 метра с центром в
/// (−4, 7) разряд координаты — около 1e-6 метра, то есть в сто раз крупнее
/// разряда радиуса. Пренебрежение им оставляет дефект на месте.
/// </para>
/// <para>
/// Решение выбрано без допуска в проверках принадлежности, чтобы не вводить
/// исключение из общего правила строгих границ библиотеки. Сдвиг величиной в
/// два последних разряда координаты не виден ни в одном применении: на
/// километре это около четверти микрометра.
/// </para>
/// </remarks>
internal static class SurfaceRadius
{
    /// <summary>
    /// Число последних разрядов, на которые уводится точка внутрь.
    /// </summary>
    private const float Shift = 2f;

    /// <summary>
    /// Радиус, меньший настоящего ровно настолько, чтобы округление сложения не
    /// вывело точку наружу.
    /// </summary>
    /// <param name="radius">Настоящий радиус фигуры.</param>
    /// <param name="basePoint">
    /// Точка, от которой отсчитывается смещение. Это не обязательно центр
    /// фигуры: у капсулы это ближайшая точка осевой линии, и у длинной капсулы
    /// она может быть на порядки дальше от начала координат, чем радиус.
    /// Ошибка округления задаётся величиной именно этой точки.
    /// </param>
    /// <returns>Радиус для вычисления точки поверхности.</returns>
    public static float For(float radius, in Vector3 basePoint)
        => Shrink(radius, Magnitude(basePoint));

    /// <summary>
    /// Двумерный вариант того же расчёта.
    /// </summary>
    /// <param name="radius">Настоящий радиус фигуры.</param>
    /// <param name="basePoint">Точка, от которой отсчитывается смещение.</param>
    /// <returns>Радиус для вычисления точки поверхности.</returns>
    public static float For(float radius, in Vector2 basePoint)
    {
        float magnitude = MathF.Max(MathF.Abs(basePoint.X), MathF.Abs(basePoint.Y));
        return Shrink(radius, magnitude);
    }

    /// <summary>
    /// Расстояние, немного превышающее расстояние до первого касания, чтобы
    /// точка, построенная по нему лучом, лежала строго внутри фигуры.
    /// </summary>
    /// <param name="distance">Расстояние до первого касания.</param>
    /// <param name="origin">Начало луча.</param>
    /// <returns>Расстояние, ведущее внутрь фигуры.</returns>
    /// <remarks>
    /// Расстояние до касания по построению кладёт точку ровно на поверхность,
    /// а проверка принадлежности строгая: измеренный выход точки наружу достигает
    /// 2.3e-5 метра при радиусе 0.22 метра, то есть примерно сотня последних
    /// разрядов. Вызывающий, который строит точку по расстоянию и сразу
    /// проверяет её, получает отказ на верном попадании.
    /// <para>
    /// Сдвиг идёт ВПЕРЁД по лучу, а не назад: расстояние до касания — это
    /// первое касание, и всё, что лежит между началом луча и ним, снаружи.
    /// Уменьшение расстояния на микроскопическую величину даёт отказ
    /// практически на каждом попадании — проверено измерением.
    /// </para>
    /// <para>
    /// Начало луча внутри фигуры расстояние не меняет: там точка входа и так
    /// строго внутри, а сдвиг увеличил бы её произвольно.
    /// </para>
    /// </remarks>
    public static float PastContact(float distance, in Vector3 origin)
    {
        if (distance <= 0f)
        {
            return distance;
        }

        // Точка на расстоянии distance от начала имеет величину не больше суммы
        // величин, а сумма нужна потому, что ошибку округления задаёт наибольшая
        // из координат результата, а не самого начала.
        float magnitude = distance + Magnitude(origin);
        return distance + (MathF.Max(distance, magnitude) * Shift * 1.1920929e-7f);
    }

    private static float Magnitude(in Vector3 point)
        => MathF.Max(MathF.Max(MathF.Abs(point.X), MathF.Abs(point.Y)), MathF.Abs(point.Z));

    private static float Shrink(float radius, float magnitude)
    {
        // Последний разряд величины не превосходит 2^-23 от неё самой, то есть
        // примерно миллионная доля. Берутся два разряда с запасом на округление
        // сложения и на то, что длина вычисляется с погрешностью.
        float error = MathF.Max(radius, magnitude) * Shift * 1.1920929e-7f;
        return radius - error;
    }
}